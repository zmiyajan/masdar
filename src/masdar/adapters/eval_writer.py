"""Write evaluation results as JSON and regenerate the Markdown comparison.

Layout under the evaluation directory (``eval/`` by default)::

    results/<pipeline>.json   one file per pipeline, machine-readable
    RESULTS.md                comparison of every file in results/, generated
    baseline.json             overall scores the regression test guards

The JSON is written with sorted keys, scores rounded to four decimals and no
timestamp, so re-running an unchanged pipeline leaves the file byte-identical
and a real change shows up as a small, readable diff.
"""

import json
from collections.abc import Callable, Sequence
from dataclasses import asdict, dataclass, fields
from pathlib import Path
from typing import Any

from masdar.adapters.files import write_atomically
from masdar.domain.errors import SourceFormatError
from masdar.domain.evaluation import EvaluationReport, GroupScores, QueryEvaluation, Scores

_DECIMALS = 4
_SCORE_FIELDS = tuple(field.name for field in fields(Scores))
# Characters a pipeline name may not bring into a file name.
_UNSAFE_IN_FILE_NAME = frozenset('/\\:*?"<>|')


@dataclass(frozen=True, slots=True)
class _Summary:
    """The part of a results file that RESULTS.md shows."""

    pipeline: str
    gold_version: str
    queries: int
    overall: Scores
    by_style: dict[str, tuple[int, Scores]]
    by_law: dict[str, tuple[int, Scores]]


class EvalResultsWriter:
    """Writes ``results/<pipeline>.json``, ``RESULTS.md`` and ``baseline.json``."""

    def __init__(self, eval_dir: Path) -> None:
        """Create a writer rooted at ``eval_dir``."""
        self._eval_dir = eval_dir
        self._results_dir = eval_dir / "results"

    @property
    def summary_path(self) -> Path:
        """Where the generated Markdown comparison is written."""
        return self._eval_dir / "RESULTS.md"

    @property
    def baseline_path(self) -> Path:
        """Where the regression baseline is written."""
        return self._eval_dir / "baseline.json"

    def write(self, reports: Sequence[EvaluationReport]) -> list[Path]:
        """Write one JSON file per report, then regenerate ``RESULTS.md``.

        The comparison covers every file in ``results/``, including pipelines
        evaluated in earlier runs, so evaluating one pipeline never drops the
        others from the table.

        Returns:
            The JSON files written, in the order of ``reports``.

        Raises:
            SourceFormatError: If a pipeline name cannot be a file name, or an
                existing results file cannot be read.
        """
        self._results_dir.mkdir(parents=True, exist_ok=True)
        paths = []
        for report in reports:
            path = self._results_dir / f"{_file_stem(report.pipeline)}.json"
            write_atomically(path, _dump(report_to_json(report)))
            paths.append(path)
        summaries = [_read_summary(path) for path in sorted(self._results_dir.glob("*.json"))]
        write_atomically(self.summary_path, _render(summaries).encode("utf-8"))
        return paths

    def write_baseline(self, report: EvaluationReport) -> Path:
        """Record ``report``'s overall scores as the regression baseline."""
        self._eval_dir.mkdir(parents=True, exist_ok=True)
        baseline = {
            "pipeline": report.pipeline,
            "gold_version": report.gold_version,
            "overall": _scores(report.overall),
        }
        write_atomically(self.baseline_path, _dump(baseline))
        return self.baseline_path


def report_to_json(report: EvaluationReport) -> dict[str, Any]:
    """The JSON document for one report (per-question detail included)."""
    return {
        "pipeline": report.pipeline,
        "gold_version": report.gold_version,
        "queries": len(report.queries),
        "overall": _scores(report.overall),
        # Lists, not objects: sort_keys would reorder an object, and the group
        # order (formal, dialect, paraphrase; laws as in the gold set) is meaningful.
        "by_style": [_group(group) for group in report.by_style],
        "by_law": [_group(group) for group in report.by_law],
        "per_query": [_query(query) for query in report.queries],
    }


def _render(summaries: Sequence[_Summary]) -> str:
    # Best nDCG@10 first, ties by name, so the row order is deterministic.
    rows = sorted(summaries, key=lambda s: (-s.overall.ndcg_at_10, s.pipeline))
    lines = [
        "# Retrieval results",
        "",
        "**Generated by `masdar eval` from `eval/results/*.json`. Do not edit by hand.**",
        "",
        "Article-level metrics on the gold questions (chunks are collapsed to articles first).",
        "Recall and MRR count any judged article as relevant; nDCG@10 uses the grades",
        "(2 = answers, 1 = related). With one annotator and 82 questions, differences",
        "below about 0.02 are noise. Definitions: "
        "[ADR-0006](../docs/decisions/0006-lexical-retrieval-and-evaluation.md).",
        "",
        "## Overall",
        "",
        "| Pipeline | Gold | nDCG@10 | MRR@10 | R@1 | R@3 | R@5 | R@10 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in rows:
        o = s.overall
        cells = (o.ndcg_at_10, o.mrr_at_10, o.recall_at_1, o.recall_at_3, o.recall_at_5)
        lines.append(
            f"| `{s.pipeline}` | {s.gold_version} ({s.queries}) | "
            + " | ".join(f"{value:.3f}" for value in (*cells, o.recall_at_10))
            + " |"
        )
    lines += _breakdown("nDCG@10 by question style", rows, lambda s: s.by_style)
    lines += _breakdown("nDCG@10 by law", rows, lambda s: s.by_law)
    return "\n".join(lines) + "\n"


def _breakdown(
    title: str,
    rows: Sequence[_Summary],
    groups_of: Callable[[_Summary], dict[str, tuple[int, Scores]]],
) -> list[str]:
    columns: dict[str, int] = {}
    for summary in rows:
        for name, (count, _) in groups_of(summary).items():
            columns.setdefault(name, count)
    lines = [
        "",
        f"## {title}",
        "",
        "| Pipeline | " + " | ".join(f"{name} ({n})" for name, n in columns.items()) + " |",
        "|---|" + "---|" * len(columns),
    ]
    for summary in rows:
        groups = groups_of(summary)
        cells = [f"{groups[name][1].ndcg_at_10:.3f}" if name in groups else "–" for name in columns]
        lines.append(f"| `{summary.pipeline}` | " + " | ".join(cells) + " |")
    return lines


def _scores(scores: Scores) -> dict[str, float]:
    return {name: round(value, _DECIMALS) for name, value in asdict(scores).items()}


def _group(group: GroupScores) -> dict[str, Any]:
    return {"group": group.group, "queries": group.queries, **_scores(group.scores)}


def _query(query: QueryEvaluation) -> dict[str, Any]:
    return {
        "query_id": query.query_id,
        "style": query.style.value,
        "laws": list(query.laws),
        "first_answer_rank": query.first_answer_rank,
        "ranking": list(query.ranking),
        **_scores(query.scores),
    }


def _dump(document: dict[str, Any]) -> bytes:
    text = json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True)
    return (text + "\n").encode("utf-8")


def _file_stem(pipeline: str) -> str:
    if not pipeline.strip() or pipeline.startswith(".") or _UNSAFE_IN_FILE_NAME & set(pipeline):
        raise SourceFormatError(f"Pipeline name {pipeline!r} cannot be used as a file name")
    return pipeline


def _read_summary(path: Path) -> _Summary:
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
        return _Summary(
            pipeline=str(document["pipeline"]),
            gold_version=str(document["gold_version"]),
            queries=int(document["queries"]),
            overall=_parse_scores(document["overall"]),
            by_style=_parse_groups(document["by_style"]),
            by_law=_parse_groups(document["by_law"]),
        )
    except json.JSONDecodeError as error:
        raise SourceFormatError(f"{path}: invalid JSON: {error}") from error
    except (KeyError, TypeError, ValueError, AttributeError) as error:
        raise SourceFormatError(f"{path}: not an evaluation result: {error!r}") from error


def _parse_scores(record: dict[str, Any]) -> Scores:
    return Scores(**{name: float(record[name]) for name in _SCORE_FIELDS})


def _parse_groups(records: list[dict[str, Any]]) -> dict[str, tuple[int, Scores]]:
    return {str(group["group"]): (int(group["queries"]), _parse_scores(group)) for group in records}
